    const {rows}=await pool.query("UPDATE applications SET status=$3,updated_at=NOW() WHERE id=$1 AND user_id=$2 RETURNING id,scheme_id,status,details,created_at,updated_at",[payload.applicationId,payload.userId,payload.status]);
